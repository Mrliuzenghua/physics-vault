export function createHtmlPresentation(input, { resourceRoot, projectRoot }) {
  const normalized = normalizeInput(input);
  const audit = auditHtmlPresentationTemplate(resourceRoot);
  if (!audit.passed) fail(`HTML 课件模板结构检查失败：缺少 ${audit.missing_signatures.join(', ')}`);
  const output = outputPath(resourceRoot);
  const requestedOperationId = operationId(input.operation_id);
  const fingerprint = requestFingerprint({ ...normalized, operation_id: undefined });
  const existing = findOperationResult(output, requestedOperationId, fingerprint);
  if (existing) {
    return { status: 'existing', source_path: existing, operation_id: requestedOperationId, idempotent: true, template_sha256: audit.actual_sha256 };
  }
  const sequence = nextSequence(output);
  const filename = `${sequence}-${safeFilePart(normalized.title)}-HTML.html`;
  const sourcePath = path.resolve(output, filename);
  if (!within(sourcePath, output)) fail('生成的 HTML 文件路径不合法。');
  const images = imagePlan(normalized, resourceRoot, projectRoot, sequence);
  const template = fs.readFileSync(audit.template_file, 'utf8');
  const { rendered, pageCount } = renderPresentation(template, normalized, images, requestedOperationId, fingerprint);
  if (input.dry_run === true) {
    return {
      status: 'preview', source_path: sourcePath, output_directory: output, sequence,
      page_count: pageCount, question_count: normalized.questions.length,
      image_count: images.flat().length, template_sha256: audit.actual_sha256,
      operation_id: requestedOperationId, message: '预览不会写入教学资源库。',
    };
  }
  outputPath(resourceRoot, true);
  fs.writeFileSync(sourcePath, rendered, { encoding: 'utf8', flag: 'wx' });
  try {
    for (const item of images.flat()) {
      fs.copyFileSync(item.source, path.join(output, 'images', item.filename), fs.constants.COPYFILE_EXCL);
    }
  } catch (error) {
    fs.rmSync(sourcePath, { force: true });
    throw error;
  }
  return {
    status: 'created', source_path: sourcePath, output_directory: output, images_directory: path.join(output, 'images'),
    sequence, page_count: pageCount, question_count: normalized.questions.length, image_count: images.flat().length,
    template_sha256: audit.actual_sha256, operation_id: requestedOperationId, idempotent: false,
    next_action: '调用 validate_html_presentation 检查页面、占位符和图片引用，然后用浏览器打开 source_path 上课。',
  };
}

export function validateHtmlPresentation(input, { resourceRoot }) {
  const output = outputPath(resourceRoot);
  const source = path.resolve(requiredString(input.source_path, 'source_path', 1000));
  if (!within(source, output) || path.extname(source).toLowerCase() !== '.html') fail(`source_path 必须是 ${OUTPUT_DIRECTORY} 内的 .html 文件。`);
  if (!fs.existsSync(source)) fail(`HTML 课件不存在：${source}`);
  const body = fs.readFileSync(source, 'utf8');
  if (!body.includes(GENERATED_MARKER)) fail('只允许校验由 Physics Vault HTML 课件 MCP 创建的文件。');
  const unresolved = [...body.matchAll(/\{\{[^}]+\}\}/g)].map((match) => match[0]);
  const localImages = [...body.matchAll(/<img\s+[^>]*src="(\.\/[^\"]+)"/g)].map((match) => decodeURIComponent(match[1]));
  const missingImages = localImages.filter((relative) => {
    const candidate = path.resolve(path.dirname(source), relative);
    return !within(candidate, output) || !fs.existsSync(candidate);
  });
  const slideCount = (body.match(/<section class="slide(?:\s|\")/g) ?? []).length;
  const questionCount = (body.match(/<section class="slide slide--question">/g) ?? []).length;
  const errors = [];
  if (slideCount === 0) errors.push('未检测到幻灯片页面。');
  if (questionCount === 0) errors.push('未检测到题目页面。');
  if (unresolved.length > 0) errors.push(`仍有 ${unresolved.length} 个未替换占位符。`);
  if (missingImages.length > 0) errors.push(`有 ${missingImages.length} 个图片引用缺失。`);
  return {
    status: errors.length === 0 ? 'validated' : 'invalid', source_path: source,
    slide_count: slideCount, question_count: questionCount, local_image_count: localImages.length,
    unresolved_placeholders: unresolved, missing_images: missingImages, errors,
    warnings: body.includes('https://cdn.jsdelivr.net/npm/mathjax') ? ['公式依赖在线 MathJax；离线课堂请提前确认网络。'] : [],
  };
}

